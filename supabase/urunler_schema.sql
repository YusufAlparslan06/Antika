create or replace function public.satis_olustur(
  p_urun_id bigint,
  p_adet integer,
  p_birim_fiyat numeric,
  p_alici text default ''
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_urun_adi text;
  v_birim_maliyet numeric(12,2);
  v_satis_id bigint;
begin
  if not public.kullanici_yetkili_mi('personel') then
    raise exception 'Satış kaydı için personel veya yönetici yetkisi gerekir.';
  end if;
  if p_adet <= 0 then
    raise exception 'Satış adedi sıfırdan büyük olmalıdır.';
  end if;
  if p_birim_fiyat < 0 then
    raise exception 'Birim fiyat negatif olamaz.';
  end if;

  perform set_config('app.stock_movement_type', 'Satış', true);

  update public.urunler
  set stok = stok - p_adet
  where id = p_urun_id and stok >= p_adet
  returning ad, coalesce(alis_fiyati, 0) + coalesce(ek_masraf, 0)
  into v_urun_adi, v_birim_maliyet;

  if not found then
    raise exception 'Ürün bulunamadı veya stok miktarı yetersiz.';
  end if;

  insert into public.satislar (
    urun_id, urun_adi, adet, birim_fiyat, birim_maliyet, alici
  )
  values (
    p_urun_id, v_urun_adi, p_adet, p_birim_fiyat, v_birim_maliyet,
    coalesce(p_alici, '')
  )
  returning id into v_satis_id;

  return v_satis_id;
end;
$$;

