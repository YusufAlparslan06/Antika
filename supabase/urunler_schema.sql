-- Antika stok uygulaması için Supabase tablo yapısı

create table if not exists public.urunler (
  id bigint generated by default as identity primary key,
  ad text not null,
  kategori text not null default 'Diğer',
  antika_yili integer default 0,
  aciklama text default '',
  alis_fiyati numeric(12,2) default 0,
  satis_fiyati numeric(12,2) default 0,
  stok integer default 0,
  teklif text default '',
  acik_arttirma_yeri text default '',
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.acik_artirmalar (
  id bigint generated by default as identity primary key,
  urun_id bigint not null,
  baslangic_fiyati numeric(12,2) default 0,
  mevcut_teklif numeric(12,2) default 0,
  baslangic_tarihi timestamptz default now(),
  bitis_tarihi timestamptz default now(),
  durum text not null default 'Aktif',
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  constraint fk_acik_artirmalar_urun
    foreign key (urun_id) references public.urunler(id) on delete cascade
);

create table if not exists public.satislar (
  id bigint generated by default as identity primary key,
  urun_id bigint not null references public.urunler(id) on delete restrict,
  urun_adi text not null,
  adet integer not null check (adet > 0),
  birim_fiyat numeric(12,2) not null check (birim_fiyat >= 0),
  alici text not null default '',
  satis_tarihi timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

