create or replace function public.kaydet_stok_hareketi()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_onceki_stok integer;
  v_miktar integer;
  v_hareket_tipi text;
begin
  if tg_op = 'INSERT' then
    v_onceki_stok := 0;
    v_miktar := new.stok;
    v_hareket_tipi := 'İlk stok';
  else
    if old.stok is not distinct from new.stok then
      return new;
    end if;
    v_onceki_stok := old.stok;
    v_miktar := abs(new.stok - old.stok);
    if new.stok > old.stok then
      v_hareket_tipi := 'Stok girişi';
    else
      v_hareket_tipi := coalesce(
        nullif(current_setting('app.stock_movement_type', true), ''),
        'Stok çıkışı'
      );
    end if;
  end if;

  if v_miktar > 0 then
    insert into public.stok_hareketleri (
      urun_id,
      urun_adi,
      hareket_tipi,
      miktar,
      onceki_stok,
      yeni_stok
    )
    values (
      new.id,
      new.ad,
      v_hareket_tipi,
      v_miktar,
      v_onceki_stok,
      new.stok
    );
  end if;

  return new;
end;
$$;

revoke all on function public.kaydet_stok_hareketi() from public, anon,
  authenticated;

drop trigger if exists trg_urunler_stok_hareketi on public.urunler;
create trigger trg_urunler_stok_hareketi
after insert or update on public.urunler
for each row
execute function public.kaydet_stok_hareketi();

insert into public.stok_hareketleri (
  urun_id,
  urun_adi,
  hareket_tipi,
  miktar,
  onceki_stok,
  yeni_stok
)
select u.id, u.ad, 'Mevcut stok', u.stok, 0, u.stok
from public.urunler u
where u.stok > 0
  and not exists (
    select 1
    from public.stok_hareketleri h
    where h.urun_id = u.id
      and h.hareket_tipi = 'Mevcut stok'
  );

