create or replace function public.satis_olustur(
  p_urun_id bigint,
  p_adet integer,
  p_birim_fiyat numeric,
  p_alici text default ''
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_urun_adi text;
  v_satis_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Satış kaydı için giriş yapmalısınız.';
  end if;
  if p_adet <= 0 then
    raise exception 'Satış adedi sıfırdan büyük olmalıdır.';
  end if;
  if p_birim_fiyat < 0 then
    raise exception 'Birim fiyat negatif olamaz.';
  end if;

  perform set_config('app.stock_movement_type', 'Satış', true);

  update public.urunler
  set stok = stok - p_adet
  where id = p_urun_id and stok >= p_adet
  returning ad into v_urun_adi;

  if not found then
    raise exception 'Ürün bulunamadı veya stok miktarı yetersiz.';
  end if;

  insert into public.satislar (urun_id, urun_adi, adet, birim_fiyat, alici)
  values (p_urun_id, v_urun_adi, p_adet, p_birim_fiyat, coalesce(p_alici, ''))
  returning id into v_satis_id;

  return v_satis_id;
end;
$$;

