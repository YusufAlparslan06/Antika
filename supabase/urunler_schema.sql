create or replace function public.envanter_sayimini_uygula(p_sayim jsonb)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item jsonb;
  v_updated integer := 0;
  v_product_id bigint;
  v_expected integer;
  v_actual integer;
begin
  if not public.kullanici_yetkili_mi('personel') then
    raise exception 'Envanter sayımı için personel veya yönetici yetkisi gerekir.';
  end if;
  if jsonb_typeof(p_sayim) <> 'array' then
    raise exception 'Sayım verisi liste biçiminde olmalıdır.';
  end if;
  perform set_config('app.stock_movement_type', 'Envanter sayımı', true);

  for v_item in select value from jsonb_array_elements(p_sayim)
  loop
    v_product_id := (v_item ->> 'product_id')::bigint;
    v_expected := (v_item ->> 'expected_stock')::integer;
    v_actual := (v_item ->> 'counted_stock')::integer;
    if v_actual < 0 then
      raise exception 'Sayım adedi negatif olamaz.';
    end if;

    update public.urunler
    set stok = v_actual
    where id = v_product_id and stok = v_expected;

    if not found then
      raise exception
        'Ürün % sayım sırasında başka bir kullanıcı tarafından değiştirilmiş. Verileri yenileyip tekrar deneyin.',
        v_product_id;
    end if;
    v_updated := v_updated + 1;
  end loop;

  return v_updated;
end;
$$;

revoke all on function public.envanter_sayimini_uygula(jsonb)
from public, anon;
grant execute on function public.envanter_sayimini_uygula(jsonb)
to authenticated;

create or replace function public.yedek_verisini_aktar(
  p_urunler jsonb,
  p_acik_artirmalar jsonb,
  p_satislar jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item jsonb;
  v_products integer := 0;
  v_auctions integer := 0;
  v_sales integer := 0;
  v_id bigint;
begin
  if not public.kullanici_yetkili_mi('yonetici') then
    raise exception 'Yedek verisini içe aktarmak için yönetici yetkisi gerekir.';
  end if;
  if jsonb_typeof(p_urunler) <> 'array'
     or jsonb_typeof(p_acik_artirmalar) <> 'array'
     or jsonb_typeof(p_satislar) <> 'array' then
    raise exception 'Yedek dosyasının sayfa yapısı geçersiz.';
  end if;

  for v_item in select value from jsonb_array_elements(p_urunler)
  loop
    v_id := (v_item ->> 'Kayıt no')::bigint;
    if v_id <= 0 or nullif(trim(v_item ->> 'Ürün'), '') is null then
      raise exception 'Ürün satırında kayıt numarası veya ürün adı geçersiz.';
    end if;
    insert into public.urunler (
      id, ad, kategori, antika_yili, aciklama, kondisyon, satis_fiyati,
      alis_fiyati, ek_masraf, stok, minimum_stok, teklif,
      acik_arttirma_yeri, konum, foto_url, kondisyon_foto_url
    )
    values (
      v_id, v_item ->> 'Ürün', coalesce(nullif(v_item ->> 'Kategori', ''), 'Diğer'),
      coalesce(nullif(v_item ->> 'Yıl', '')::integer, 0),
      coalesce(v_item ->> 'Tarihsel geçmiş', ''),
      coalesce(v_item ->> 'Kondisyon', ''),
      coalesce(nullif(v_item ->> 'Birim değer (₺)', '')::numeric, 0),
      coalesce(nullif(v_item ->> 'Alış bedeli (₺)', '')::numeric, 0),
      coalesce(nullif(v_item ->> 'Ek masraf (₺)', '')::numeric, 0),
      coalesce(nullif(v_item ->> 'Stok', '')::integer, 0),
      coalesce(nullif(v_item ->> 'Stok uyarı eşiği', '')::integer, 3),
      coalesce(v_item ->> 'Teklif', ''),
      coalesce(v_item ->> 'Açık artırma yeri', ''),
      coalesce(v_item ->> 'Depo/raf konumu', ''),
      nullif(v_item ->> 'Ürün fotoğrafı URL', ''),
      nullif(v_item ->> 'Kondisyon fotoğrafı URL', '')
    )
    on conflict (id) do update set
      ad = excluded.ad, kategori = excluded.kategori,
      antika_yili = excluded.antika_yili, aciklama = excluded.aciklama,
      kondisyon = excluded.kondisyon, satis_fiyati = excluded.satis_fiyati,
      alis_fiyati = excluded.alis_fiyati, ek_masraf = excluded.ek_masraf,
      stok = excluded.stok, minimum_stok = excluded.minimum_stok,
      teklif = excluded.teklif, acik_arttirma_yeri = excluded.acik_arttirma_yeri,
      konum = excluded.konum, foto_url = excluded.foto_url,
      kondisyon_foto_url = excluded.kondisyon_foto_url;
    v_products := v_products + 1;
  end loop;

  for v_item in select value from jsonb_array_elements(p_acik_artirmalar)
  loop
    v_id := (v_item ->> 'Kayıt no')::bigint;
    insert into public.acik_artirmalar (
      id, urun_id, baslangic_fiyati, mevcut_teklif, baslangic_tarihi,
      bitis_tarihi, durum, kazanan, son_satis_fiyati, odeme_durumu,
      teslimat_durumu
    )
    values (
      v_id, (v_item ->> 'Ürün kayıt no')::bigint,
      coalesce(nullif(v_item ->> 'Başlangıç fiyatı (₺)', '')::numeric, 0),
      coalesce(nullif(v_item ->> 'Mevcut teklif (₺)', '')::numeric, 0),
      (v_item ->> 'Başlangıç tarihi')::timestamptz,
      (v_item ->> 'Bitiş tarihi')::timestamptz,
      coalesce(v_item ->> 'Durum', 'Aktif'),
      coalesce(v_item ->> 'Kazanan', ''),
      coalesce(nullif(v_item ->> 'Son satış fiyatı (₺)', '')::numeric, 0),
      coalesce(v_item ->> 'Ödeme durumu', 'Bekliyor'),
      coalesce(v_item ->> 'Teslimat durumu', 'Bekliyor')
    )
    on conflict (id) do update set
      urun_id = excluded.urun_id,
      baslangic_fiyati = excluded.baslangic_fiyati,
      mevcut_teklif = excluded.mevcut_teklif,
      baslangic_tarihi = excluded.baslangic_tarihi,
      bitis_tarihi = excluded.bitis_tarihi, durum = excluded.durum,
      kazanan = excluded.kazanan, son_satis_fiyati = excluded.son_satis_fiyati,
      odeme_durumu = excluded.odeme_durumu,
      teslimat_durumu = excluded.teslimat_durumu;
    v_auctions := v_auctions + 1;
  end loop;

  for v_item in select value from jsonb_array_elements(p_satislar)
  loop
    v_id := (v_item ->> 'Kayıt no')::bigint;
    insert into public.satislar (
      id, urun_id, urun_adi, adet, birim_fiyat, birim_maliyet, alici,
      satis_tarihi
    )
    values (
      v_id, nullif(v_item ->> 'Ürün kayıt no', '')::bigint,
      v_item ->> 'Ürün', (v_item ->> 'Adet')::integer,
      (v_item ->> 'Birim fiyat (₺)')::numeric,
      coalesce(nullif(v_item ->> 'Birim maliyet (₺)', '')::numeric, 0),
      coalesce(v_item ->> 'Alıcı', ''),
      (v_item ->> 'Satış tarihi')::timestamptz
    )
    on conflict (id) do update set
      urun_id = excluded.urun_id,
      urun_adi = excluded.urun_adi, adet = excluded.adet,
      birim_fiyat = excluded.birim_fiyat,
      birim_maliyet = excluded.birim_maliyet, alici = excluded.alici,
      satis_tarihi = excluded.satis_tarihi;
    v_sales := v_sales + 1;
  end loop;

  perform setval(
    pg_get_serial_sequence('public.urunler', 'id'),
    greatest(coalesce((select max(id) from public.urunler), 1), 1),
    exists (select 1 from public.urunler)
  );
  perform setval(
    pg_get_serial_sequence('public.acik_artirmalar', 'id'),
    greatest(coalesce((select max(id) from public.acik_artirmalar), 1), 1),
    exists (select 1 from public.acik_artirmalar)
  );
  perform setval(
    pg_get_serial_sequence('public.satislar', 'id'),
    greatest(coalesce((select max(id) from public.satislar), 1), 1),
    exists (select 1 from public.satislar)
  );

  return jsonb_build_object(
    'products', v_products, 'auctions', v_auctions, 'sales', v_sales
  );
end;
$$;

revoke all on function public.yedek_verisini_aktar(jsonb, jsonb, jsonb)
from public, anon;
grant execute on function public.yedek_verisini_aktar(jsonb, jsonb, jsonb)
to authenticated;

