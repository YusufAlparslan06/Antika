create or replace function public.yonetici_kullanicilari()
returns table (
  kullanici_id uuid,
  eposta text,
  ad text,
  rol text
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.kullanici_yetkili_mi('yonetici') then
    raise exception 'Kullanıcı rollerini yalnızca yöneticiler görüntüleyebilir.';
  end if;

  return query
  select
    u.id,
    coalesce(u.email, '')::text,
    coalesce(u.raw_user_meta_data ->> 'full_name', '')::text,
    coalesce(r.rol, 'personel')::text
  from auth.users u
  left join public.kullanici_rolleri r on r.kullanici_id = u.id
  order by lower(coalesce(u.email, ''));
end;
$$;

create or replace function public.yonetici_rol_degistir(
  p_kullanici_id uuid,
  p_yeni_rol text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.kullanici_yetkili_mi('yonetici') then
    raise exception 'Rol değiştirmek için yönetici yetkisi gerekir.';
  end if;
  if p_yeni_rol not in ('yonetici', 'personel') then
    raise exception 'Geçersiz kullanıcı rolü.';
  end if;
  if p_kullanici_id = auth.uid() then
    raise exception 'Kendi rolünüzü bu ekrandan değiştiremezsiniz.';
  end if;
  if not exists (select 1 from auth.users u where u.id = p_kullanici_id) then
    raise exception 'Kullanıcı bulunamadı.';
  end if;
  if p_yeni_rol = 'personel'
     and exists (
       select 1 from public.kullanici_rolleri r
       where r.kullanici_id = p_kullanici_id and r.rol = 'yonetici'
     )
     and not exists (
       select 1 from public.kullanici_rolleri r
       where r.rol = 'yonetici' and r.kullanici_id <> p_kullanici_id
     ) then
    raise exception 'Son yöneticinin rolü personel olarak değiştirilemez.';
  end if;

  insert into public.kullanici_rolleri (kullanici_id, rol)
  values (p_kullanici_id, p_yeni_rol)
  on conflict (kullanici_id)
  do update set rol = excluded.rol;
end;
$$;

