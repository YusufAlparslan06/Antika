create or replace function public.kaydet_islem_gecmisi()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_row jsonb;
  v_record_id bigint;
  v_product_id bigint;
  v_action text;
  v_user_id uuid := auth.uid();
  v_user_name text := coalesce(
    nullif(auth.jwt() -> 'user_metadata' ->> 'full_name', ''),
    nullif(auth.jwt() ->> 'email', ''),
    'Bilinmeyen kullanıcı'
  );
  v_user_role text := 'personel';
begin
  if v_user_id is not null then
    select r.rol into v_user_role
    from public.kullanici_rolleri r
    where r.kullanici_id = v_user_id;
  end if;

  if tg_op <> 'INSERT' then v_old := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then v_new := to_jsonb(new); end if;
  v_row := coalesce(v_new, v_old);
  v_record_id := nullif(v_row ->> 'id', '')::bigint;

  if tg_table_name = 'urunler' then
    v_product_id := v_record_id;
  elsif tg_table_name = 'acik_artirmalar' then
    v_product_id := nullif(v_row ->> 'urun_id', '')::bigint;
  elsif tg_table_name = 'satislar' then
    v_product_id := nullif(v_row ->> 'urun_id', '')::bigint;
  end if;

  v_action := case tg_op
    when 'INSERT' then 'Eklendi'
    when 'UPDATE' then 'Güncellendi'
    else 'Silindi'
  end;

  insert into public.islem_gecmisi (
    kayit_turu, kayit_id, urun_id, islem, yapan_id, yapan_adi, yapan_rol,
    ayrintilar
  )
  values (
    tg_table_name, v_record_id, v_product_id, v_action, v_user_id,
    left(v_user_name, 160), coalesce(v_user_role, 'personel'),
    jsonb_build_object('onceki', v_old, 'yeni', v_new)
  );
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

revoke all on function public.kaydet_islem_gecmisi()
from public, anon, authenticated;

